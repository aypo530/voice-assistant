NOWS = ["2026-10-23T01:40", "2026-10-21T00:58", "2026-10-26T23:30", "2026-12-31T22:15", "2026-03-01T09:00", "2026-10-25T12:00", "2026-02-27T18:45", "2026-10-23T14:20"]


def make_scenarios(n, seed=7):
    rnd = random.Random(seed)
    out = []
    kinds = list(PHRASES)
    weights = [4, 2, 3, 3, 2, 3, 1]
    for i in range(n):
        steps = []
        for _ in range(rnd.randint(3, 9)):
            k = rnd.choices(kinds, weights)[0]
            steps.append(rnd.choice(PHRASES[k]))
        out.append({"now": rnd.choice(NOWS), "steps": steps})
    return out


class Fixed(datetime):
    fixed = None

    @classmethod
    def now(cls, tz=None):
        return cls.fixed.astimezone(tz) if tz else cls.fixed


def run_python(scenarios):
    assistant.datetime = Fixed
    results = []
    for sc in scenarios:
        if config.DATA_FILE.exists():
            config.DATA_FILE.unlink()
        storage.init()
        a = assistant.Assistant()
        Fixed.fixed = datetime.strptime(sc["now"], "%Y-%m-%dT%H:%M").replace(tzinfo=timezone.utc)
        replies = []
        for t in sc["steps"]:
            r = a.handle("s", "UTC", text=t)
            replies.append([r["intent"], r["reply"]])
        items = [[r["kind"], r["title"], r["due_date"], r["due_time"], r["status"]] for r in storage.all_items("s")]
        results.append({"replies": replies, "items": items})
    return results


def main(n):
    scenarios = make_scenarios(n)
    path = Path(tempfile.mkdtemp()) / "sc.json"
    path.write_text(json.dumps(scenarios, ensure_ascii=False), encoding="utf-8")
    js = json.loads(subprocess.run(["node", str(ROOT / "offline_runner.js"), str(path)], check=True, capture_output=True, text=True).stdout)
    py = run_python(scenarios)
    bad = 0
    for sc, a, b in zip(scenarios, py, js):
        if a != b:
            bad += 1
            if bad <= 8:
                print("=== РАСХОЖДЕНИЕ", sc["now"])
                for i, t in enumerate(sc["steps"]):
                    pa, pb = a["replies"][i], b["replies"][i]
                    mark = "  " if pa == pb else "!!"
                    print(f"{mark} {t!r}\n     py: {pa}\n     js: {pb}")
                if a["items"] != b["items"]:
                    print("   items py:", a["items"], "\n   items js:", b["items"])
    print(f"Сценариев: {len(scenarios)}, расхождений: {bad}")
    return bad


